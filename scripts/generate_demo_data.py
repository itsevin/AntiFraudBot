import asyncio
import random
from datetime import datetime, timedelta
import sys
from pathlib import Path

# 添加项目根目录到 sys.path
sys.path.append(str(Path(__file__).parent.parent))

# 初始化 NoneBot
import nonebot
from nonebot.adapters.onebot.v11 import Adapter as OneBotAdapter
nonebot.init()
driver = nonebot.get_driver()
driver.register_adapter(OneBotAdapter)
nonebot.load_plugin("nonebot_plugin_orm")

from nonebot_plugin_orm import get_session
from src.database.models import DetectionLog, AIAnalysisLog, GroupConfig, ChatbotLog, DailyBriefing

async def generate_data():
    print("开始生成演示数据...")

    async with get_session() as session:
        # 1. 生成群组配置
        groups = []
        for i in range(10):
            group_id = f"12345678{i}"
            group = GroupConfig(
                group_id=group_id,
                keyword_detection=True,
                url_detection=True,
                ai_analysis=True,
                geo_location=f"{20 + random.random()*30},{80 + random.random()*40}", # 随机中国坐标
                created_at=datetime.now() - timedelta(days=30)
            )
            groups.append(group_id)
            session.add(group)

        # 2. 生成拦截记录 (DetectionLog)
        keywords = ["转账", "安全账户", "中奖", "刷单", "理财", "退款"]
        for i in range(50):
            detected_at = datetime.now() - timedelta(minutes=random.randint(0, 24*60))
            risk_level = random.randint(1, 5)
            # 估算价值
            val = 0
            if risk_level >= 4: val = random.randint(10000, 100000)
            elif risk_level >= 2: val = random.randint(1000, 10000)

            log = DetectionLog(
                group_id=random.choice(groups),
                user_id=f"user_{random.randint(100, 999)}",
                keyword=random.choice(keywords),
                message_content="演示消息内容...",
                risk_level=risk_level,
                saved_value_estimate=val,
                detected_at=detected_at
            )
            session.add(log)

        # 3. 生成 AI 分析记录 (AIAnalysisLog)
        types = ["刷单返利", "虚假投资", "冒充公检法", "杀猪盘", "网络贷款"]
        for i in range(20):
            analyzed_at = datetime.now() - timedelta(minutes=random.randint(0, 12*60))
            is_high = random.choice([True, False])

            trace = None
            if is_high:
                trace = "用户提到‘安全账户’ -> 触发冒充公检法特征 -> 检查上下文 -> 确认为高危话术\n思维链：\n1. 分析关键词...\n2. 匹配诈骗模型..."

            log = AIAnalysisLog(
                group_id=random.choice(groups),
                user_id=f"user_{random.randint(100, 999)}",
                input_text="演示输入文本...",
                risk_level="高危" if is_high else "低危",
                fraud_type=random.choice(types) if is_high else None,
                analysis_result="AI 详细分析结果...",
                reasoning_trace=trace,
                model_used="deepseek-chat",
                analyzed_at=analyzed_at
            )
            session.add(log)

        # 4. 生成 AI 聊天日志 (ChatbotLog)
        for i in range(30):
            created_at = datetime.now() - timedelta(minutes=random.randint(0, 24*60))
            log = ChatbotLog(
                user_id=f"user_{random.randint(100, 999)}",
                group_id=random.choice(groups),
                user_message="如何防范诈骗？",
                bot_response="请保持警惕...",
                rag_context="相关知识库内容...",
                model_used="deepseek-chat",
                response_time=random.randint(500, 3000),
                latency_ms=random.randint(500, 3000),
                token_usage=random.randint(100, 500),
                sentiment_score=random.uniform(-0.5, 0.8),
                created_at=created_at
            )
            session.add(log)

        # 5. 生成日报
        today = datetime.now().replace(hour=0, minute=0, second=0, microsecond=0)
        report = DailyBriefing(
            report_date=today,
            content="""# 2024年XX月XX日 全网反诈态势研判

## 🔴 整体态势 HIGH THREAT
今日全网诈骗活跃度呈**上升**趋势。拦截诈骗信息 **50+** 条，成功预估挽回损失 **¥1,250,000**。

## ⚠️ 高发风险
1. **刷单返利**：占比 45%，主要针对大学生群体。
2. **虚假投资**：占比 30%，利用即时通讯软件拉群诱导。

## 🛡️ 防护建议
建议各群管理员开启"链接检测"功能，并重点关注夜间时段的异常消息。

*(Generated by AntiFraudBot AI Tactical Unit)*""",
            generated_at=datetime.now()
        )
        session.add(report)

        try:
            await session.commit()
            print("✅ 演示数据生成成功！请重启后端并刷新网页。")
        except Exception as e:
            await session.rollback()
            print(f"❌ 生成失败: {e}")

if __name__ == "__main__":
    asyncio.run(generate_data())
